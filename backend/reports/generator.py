def generate_cse_report_html(db: Session, cse_id: str) -> str:
    cse = db.query(CSE).filter(CSE.cse_id == cse_id).first()
    if not cse:
        return "<h1>CSE Not Found</h1>"

    findings = db.query(Finding).filter(Finding.cse_id == cse_id).all()
    remediations = db.query(RemediationAction).filter(RemediationAction.cse_id == cse_id).all()
    alerts_count = db.query(Alert).filter(Alert.cse_id == cse_id).count()
    cases_count = db.query(Case).filter(Case.cse_id == cse_id).count()
    crit_alerts = db.query(Alert).filter(Alert.cse_id == cse_id, Alert.severity == "Critical").all()
    crit_count = len(crit_alerts)
    unescalated_crit = len([a for a in crit_alerts if not a.escalated])

    findings_blocks = ""
    for f in findings:
        sev_color = "#e11d48" if f.severity == "Critical" else ("#f59e0b" if f.severity == "High" else "#38bdf8")
        rec_actions = json.loads(f.recommended_actions_json) if f.recommended_actions_json else []
        evidence = json.loads(f.evidence_json) if f.evidence_json else []
        metrics = json.loads(f.metrics_json) if f.metrics_json else {}

        actions_html = "".join([f"<li>{a}</li>" for a in rec_actions])
        
